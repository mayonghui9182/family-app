-- 每日功能使用独立历史；账号仍引用主业务账号。
CREATE TABLE daily_app.daily_settings (
    user_id BIGINT PRIMARY KEY REFERENCES public.users(id),
    enabled BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE daily_app.daily_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id),
    plan_date DATE NOT NULL,
    kind VARCHAR(10) NOT NULL CHECK (kind IN ('PLAN', 'REVIEW')),
    content TEXT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    feedback TEXT,
    generated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (user_id, plan_date, kind)
);
